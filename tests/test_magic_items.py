"""Magic items, runes and abilities: the data, buying them, and their effects.

Every item on the site is recorded (magic_items_data.py, generated by
tools/transcribe_items.py) with a status saying how much of it the engine
models. These tests hold the data to that status, sweep every item a faction
can buy through a real duel, and pin the effects of items whose wording is
easy to misread.
"""

from __future__ import annotations

import io
